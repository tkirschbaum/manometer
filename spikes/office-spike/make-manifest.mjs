#!/usr/bin/env node
// Generates the spike manifest.
//   node make-manifest.mjs                              -> manifest.xml        (https://localhost:3443)
//   node make-manifest.mjs https://abc.trycloudflare.com -> manifest.tunnel.xml (quick tunnel)
// Both variants share the same add-in Id on purpose: a .pptx saved on one machine
// must open with the spike on the other machine. Sideload only one variant per machine.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ADDIN_ID = 'bdd5caae-039b-4743-b59a-ce814393bac2';
const here = dirname(fileURLToPath(import.meta.url));

const arg = process.argv[2];
const base = (arg ?? 'https://localhost:3443').replace(/\/+$/, '');
let parsed;
try {
  parsed = new URL(base);
} catch {
  console.error(`Not a URL: ${base}`);
  process.exit(1);
}
if (parsed.protocol !== 'https:') {
  console.error('Office add-ins must be served over HTTPS.');
  process.exit(1);
}
const origin = parsed.origin;
const outFile = arg ? 'manifest.tunnel.xml' : 'manifest.xml';

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Phase 0 spike manifest. Generated by make-manifest.mjs; do not edit by hand. -->
<OfficeApp xmlns="http://schemas.microsoft.com/office/appforoffice/1.1"
           xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
           xsi:type="ContentApp">
  <Id>${ADDIN_ID}</Id>
  <Version>0.0.1.0</Version>
  <ProviderName>TK Webwerk</ProviderName>
  <DefaultLocale>en-US</DefaultLocale>
  <DisplayName DefaultValue="Pulse Office Spike" />
  <Description DefaultValue="Phase 0 diagnostics for the Pulse content add-in. Not for production use." />
  <IconUrl DefaultValue="${origin}/assets/icon-32.png" />
  <HighResolutionIconUrl DefaultValue="${origin}/assets/icon-64.png" />
  <SupportUrl DefaultValue="${origin}/logs" />
  <AppDomains>
    <AppDomain>${origin}</AppDomain>
  </AppDomains>
  <Hosts>
    <Host Name="Presentation" />
  </Hosts>
  <DefaultSettings>
    <SourceLocation DefaultValue="${origin}/index.html" />
    <RequestedWidth>960</RequestedWidth>
    <RequestedHeight>540</RequestedHeight>
  </DefaultSettings>
  <Permissions>ReadWriteDocument</Permissions>
  <AllowSnapshot>true</AllowSnapshot>
</OfficeApp>
`;

writeFileSync(join(here, outFile), xml);
console.log(`Wrote ${outFile} for ${origin}`);
